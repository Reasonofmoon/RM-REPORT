import { getProviderConfig, resolveApiKey } from './aiModels.js'

const SYSTEM_PROMPT =
  '당신은 중등 영어 교육 전문가입니다. 진단 결과를 바탕으로 구체적이고 실행 가능한 피드백을 JSON으로만 제공합니다. 마크다운 코드펜스 없이 순수 JSON 객체만 출력하세요.'

/**
 * AI 피드백 생성 서비스
 * - OpenAI / Gemini / Claude(Anthropic) 지원
 * - 각 제공사 가성비 모델을 기본 사용
 * - 성적표 생성 시 키가 있으면 자동 호출
 */
export class AIFeedbackService {
  constructor(apiKey, provider = 'openai', options = {}) {
    this.provider = provider in { openai: 1, gemini: 1, anthropic: 1 } ? provider : 'openai'
    this.config = getProviderConfig(this.provider)
    this.apiKey = resolveApiKey(this.provider, apiKey)
    this.model = options.model || this.config.model
    this.baseURL = this.config.baseURL
  }

  async generateFeedback(studentInfo, gradeData, analysis, levelDiagnosis) {
    if (!this.apiKey) {
      throw new Error('API 키가 설정되지 않았습니다. AI 설정 탭에서 키를 입력하세요.')
    }

    const prompt = this.createPrompt(studentInfo, gradeData, analysis, levelDiagnosis)

    try {
      const response = await this.callAI(prompt)
      const feedback = this.parseFeedback(response)
      return {
        ...feedback,
        _meta: {
          provider: this.provider,
          model: this.model,
          modelLabel: this.config.modelLabel,
          autoGenerated: true,
        },
      }
    } catch (error) {
      console.error('AI 피드백 생성 오류:', error)
      // Gemini/Claude 폴백 모델 1회 재시도
      if (this.config.fallbackModels?.length) {
        for (const fb of this.config.fallbackModels) {
          try {
            this.model = fb
            const response = await this.callAI(prompt)
            const feedback = this.parseFeedback(response)
            return {
              ...feedback,
              _meta: {
                provider: this.provider,
                model: fb,
                modelLabel: `${this.config.modelLabel} (fallback: ${fb})`,
                autoGenerated: true,
              },
            }
          } catch (e2) {
            console.warn(`fallback model failed: ${fb}`, e2)
          }
        }
      }
      throw new Error('AI 피드백 생성 중 오류가 발생했습니다: ' + error.message)
    }
  }

  createPrompt(studentInfo, gradeData, analysis, levelDiagnosis) {
    const gradeDataSummary = gradeData
      .map(
        (item) =>
          `문항 ${item.no}: ${item.correct === 'O' ? '정답' : item.correct === 'P' ? '부분' : '오답'} (${item.score}/${item.maxScore}점, ${item.detailArea || item.area}, 난이도: ${item.difficulty}, 수준: ${item.level})`
      )
      .join('\n')

    const levelSummary = (levelDiagnosis?.rates || [])
      .map((r) => `${r.level}: ${Math.round(r.rate * 100)}% (${r.score}/${r.max})`)
      .join(', ')

    return `당신은 중등 영어 진단평가 전문 교사입니다. 아래 레벨테스트 결과를 분석해 개인화된 피드백을 JSON으로 작성하세요.

**학생 정보:**
- 이름: ${studentInfo.name}
- 시험명: ${studentInfo.testName}
- 응시일: ${studentInfo.testDate}

**문항별 결과:**
${gradeDataSummary}

**분석 결과:**
- 총점: ${analysis.totalScore}/${analysis.totalMaxScore}점 (${analysis.percentage}%)
- 가장 강한 영역: ${analysis.strongestArea}
- 보완이 필요한 영역: ${analysis.weakestArea}
- 수준별 정답률: ${levelSummary}
- 추천 학습 레벨: ${levelDiagnosis?.recommended || '미정'}
- 학년·상중하 진단이 있으면 총평에 자연스럽게 포함하세요.

다음 JSON 형식으로만 응답하세요 (다른 텍스트 금지):
{
  "overallAssessment": "전체 성과 평가 2-3문장 (추천 레벨·상중하 언급)",
  "strengths": "강점 분석",
  "weaknesses": "약점 분석",
  "recommendations": ["학습 제언1", "학습 제언2", "학습 제언3"],
  "motivationalMessage": "격려 메시지 1-2문장"
}`
  }

  async callAI(prompt) {
    if (this.provider === 'openai') return this.callOpenAI(prompt)
    if (this.provider === 'gemini') return this.callGemini(prompt)
    if (this.provider === 'anthropic') return this.callAnthropic(prompt)
    throw new Error(`지원하지 않는 제공사: ${this.provider}`)
  }

  async callOpenAI(prompt) {
    const response = await fetch(this.baseURL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${this.apiKey}`,
      },
      body: JSON.stringify({
        model: this.model,
        messages: [
          { role: 'system', content: SYSTEM_PROMPT },
          { role: 'user', content: prompt },
        ],
        temperature: 0.6,
        max_tokens: 1200,
        response_format: { type: 'json_object' },
      }),
    })
    return this.handleHttp(response)
  }

  async callGemini(prompt) {
    const url = `${this.baseURL}/models/${this.model}:generateContent?key=${encodeURIComponent(this.apiKey)}`
    const response = await fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: SYSTEM_PROMPT }] },
        contents: [{ role: 'user', parts: [{ text: prompt }] }],
        generationConfig: {
          temperature: 0.6,
          maxOutputTokens: 1200,
          responseMimeType: 'application/json',
        },
      }),
    })
    return this.handleHttp(response)
  }

  async callAnthropic(prompt) {
    const response = await fetch(this.baseURL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': this.apiKey,
        'anthropic-version': '2023-06-01',
      },
      body: JSON.stringify({
        model: this.model,
        max_tokens: 1200,
        temperature: 0.6,
        system: SYSTEM_PROMPT,
        messages: [{ role: 'user', content: prompt }],
      }),
    })
    return this.handleHttp(response)
  }

  async handleHttp(response) {
    if (!response.ok) {
      const errorData = await response.json().catch(() => ({}))
      const msg =
        errorData.error?.message ||
        errorData.error?.status ||
        errorData.message ||
        response.statusText
      throw new Error(`API 호출 실패: ${response.status} - ${msg}`)
    }
    return response.json()
  }

  parseFeedback(response) {
    let content = ''

    if (this.provider === 'openai') {
      content = response.choices?.[0]?.message?.content || ''
    } else if (this.provider === 'gemini') {
      const parts = response.candidates?.[0]?.content?.parts || []
      content = parts.map((p) => p.text || '').join('')
    } else if (this.provider === 'anthropic') {
      content = (response.content || []).map((c) => c.text || '').join('')
    }

    if (!content) throw new Error('AI 응답에서 내용을 찾을 수 없습니다.')

    try {
      const jsonMatch = content.match(/\{[\s\S]*\}/)
      if (jsonMatch) {
        const parsed = JSON.parse(jsonMatch[0])
        // 최소 필드 보정
        return {
          overallAssessment: parsed.overallAssessment || '',
          strengths: parsed.strengths || '',
          weaknesses: parsed.weaknesses || '',
          recommendations: Array.isArray(parsed.recommendations)
            ? parsed.recommendations
            : [String(parsed.recommendations || '')],
          motivationalMessage: parsed.motivationalMessage || '',
        }
      }
      throw new Error('JSON 형식을 찾을 수 없습니다.')
    } catch (e) {
      console.error('JSON 파싱 오류:', e)
      return {
        overallAssessment: content.substring(0, 280),
        strengths: '응답 파싱에 실패해 원문 일부를 표시합니다.',
        weaknesses: 'AI 응답 형식을 확인한 뒤 다시 생성해 주세요.',
        recommendations: [
          '틀린 문법 영역을 교재로 복습하세요.',
          '독해는 주제·요지 찾기 연습을 하세요.',
          '오답 노트를 만들어 반복 학습하세요.',
        ],
        motivationalMessage: '꾸준한 복습으로 레벨을 올릴 수 있습니다!',
      }
    }
  }
}

export function generateDefaultFeedback(studentInfo, gradeData, analysis, levelDiagnosis) {
  const getPerformanceLevel = (percentage) => {
    if (percentage >= 90) return '매우 우수'
    if (percentage >= 80) return '우수'
    if (percentage >= 70) return '양호'
    if (percentage >= 60) return '보통'
    return '보완 필요'
  }

  const performanceLevel = getPerformanceLevel(analysis.percentage)
  const wrong = gradeData.filter((g) => g.correct === 'X' || g.correct === 'P')
  const wrongAreas = [...new Set(wrong.map((w) => w.detailArea || w.area))].slice(0, 4)
  const recommended = levelDiagnosis?.recommended || '중1'

  return {
    overallAssessment: `${studentInfo.name || '학생'} 님은 전체 ${analysis.totalMaxScore}점 만점에 ${analysis.totalScore}점(${analysis.percentage}%)으로 ${performanceLevel} 수준입니다. 현재 진단 기준 추천 학습 레벨은 **${recommended}** 입니다. ${analysis.strongestArea}에서 상대적으로 강점을 보였습니다.`,
    strengths: `${analysis.strongestArea} 영역에서 가장 높은 정답률을 기록했습니다. 해당 영역의 기본 개념과 문제 유형에 대한 이해도가 높습니다. 이 강점을 유지하면서 약한 영역으로 학습 범위를 확장하면 좋습니다.`,
    weaknesses: `${analysis.weakestArea} 영역이 보완이 필요합니다.${
      wrongAreas.length ? ` 특히 ${wrongAreas.join(', ')} 관련 문항에서 실수가 있었습니다.` : ''
    } 해당 문법·독해 개념을 정리한 뒤 유사 유형을 반복 연습하세요.`,
    recommendations: [
      `추천 레벨(${recommended}) 교재로 ${analysis.weakestArea} 핵심 문법을 주 3회 이상 복습하세요.`,
      wrongAreas[0]
        ? `오답 영역 「${wrongAreas[0]}」 유형 문제 10문항을 풀어 패턴을 익히세요.`
        : '오답 문항을 다시 풀어 실수 원인을 정리하세요.',
      '독해 문항은 지문을 문장 단위로 끊어 읽고, 주제 문장을 밑줄 치는 습관을 들이세요.',
      `${analysis.strongestArea}의 강점을 유지하며 주 1회 혼합 모의고사로 감을 유지하세요.`,
    ],
    motivationalMessage: `${recommended} 레벨 학습을 차근차근 이어가면 곧 다음 단계로 올라갈 수 있습니다. 지금의 진단 결과를 발판 삼아 자신 있게 공부해 보세요!`,
    _meta: {
      provider: 'rule-based',
      model: 'default',
      modelLabel: '기본 규칙 분석 (API 키 없음)',
      autoGenerated: true,
    },
  }
}
